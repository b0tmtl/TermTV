// Generates src/i18n/locales.generated.ts from every src/i18n/locales/*.json file, so adding a
// language is just adding a JSON file.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/i18n/locales');
const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
if (!files.includes('en.json')) throw new Error('en.json is required');
const lines = ['// Generated by scripts/gen-locales.mjs. Do not edit.'];
const entries = [];
for (const f of files) {
  const code = f.replace(/\.json$/, '');
  const json = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  const name = (json._meta && json._meta.name) || code;
  const ident = 'l_' + code.replace(/[^a-zA-Z0-9]/g, '_');
  lines.push(`import ${ident} from './locales/${f}';`);
  entries.push(`  ${JSON.stringify(code)}: { name: ${JSON.stringify(name)}, strings: ${ident} as Record<string, unknown> },`);
}
lines.push('', 'export const LOCALES: Record<string, { name: string; strings: Record<string, unknown> }> = {', ...entries, '};', '');
writeFileSync(join(root, 'src/i18n/locales.generated.ts'), lines.join('\n'));
